// Builds the list of words a player may set for their opponent.
// A word qualifies when it is in ENABLE (public domain), is among the 50,000 most frequent
// English words in the OpenSubtitles frequency list (hermitdave/FrequencyWords, CC BY-SA 4.0),
// is 4-8 plain letters long, and is not in tools/data/blocklist.txt.
// Outputs public/words.txt (the app's instant check) and the dictionary migration.
import { readFileSync, writeFileSync } from 'node:fs';

const lines = (f) => readFileSync(new URL(`./data/${f}`, import.meta.url), 'utf8').split(/\r?\n/);
const ok = (w) => /^[a-z]{4,8}$/.test(w);
const enable = new Set(lines('enable1.txt').map((w) => w.trim()).filter(ok));
const block = new Set(lines('blocklist.txt').join(' ').split(/\s+/).filter(Boolean));
const words = [...new Set(lines('en_50k.txt').map((l) => l.split(' ')[0]).filter(ok))]
  .filter((w) => enable.has(w) && !block.has(w))
  .sort();

writeFileSync(new URL('../public/words.txt', import.meta.url), words.join('\n') + '\n');
const sql = `-- Generated by tools/build-words.mjs. ${words.length} words.
insert into public.dictionary (word)
select unnest(string_to_array('${words.join(' ')}', ' '))
on conflict do nothing;
`;
writeFileSync(new URL('../supabase/migrations/20261122000002_dictionary.sql', import.meta.url), sql);
console.log(`${words.length} words`);
